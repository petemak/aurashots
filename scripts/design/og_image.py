"""Generate the social sharing image (assets/og-image.svg and assets/og-image.png).

Owned by visual-designer; see visual-guide.md section 13 "Social sharing image".
Re-run this whenever the tagline, the place line or the logo changes:

    python3 -m venv .venv-design && .venv-design/bin/pip install fonttools brotli
    .venv-design/bin/python scripts/design/og_image.py

Run it from the project root. It embeds assets/logo.svg as it is, converts the
text to outlines using the self-hosted fonts in assets/fonts/ (so the SVG needs
no fonts to render), writes assets/og-image.svg and renders assets/og-image.png
at 1200x630 with Inkscape.
"""

import re
import subprocess
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "assets"
FONTS = ASSETS / "fonts"

WIDTH, HEIGHT = 1200, 630
TAGLINE = "Not just photos…it’s an aura"
PLACE = "KIGALI, RWANDA"

# Colours from design-tokens.css: Noir, Pearl, Mist, Aura Pink.
NOIR, PEARL, MIST, PINK = "#0A0A0A", "#F6F1EF", "#B8ADB2", "#E0457B"


def text_path(font_file, text, size, track=0):
    """Return (svg path data, width) for `text` set in `font_file` at `size` px.

    `track` adds that many px between letters. Reads WOFF2 directly, which
    needs the brotli package.
    """
    font = TTFont(font_file)
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    scale = size / font["head"].unitsPerEm
    x, parts = 0, []
    for ch in text:
        name = cmap[ord(ch)]
        pen = SVGPathPen(glyphs)
        glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x, 0)))
        parts.append(pen.getCommands())
        x += glyphs[name].width * scale + track
    return " ".join(parts), x - track


def centred(font_file, text, size, baseline, fill, track=0):
    """Return an SVG <path> of `text` centred horizontally on the image."""
    d, w = text_path(font_file, text, size, track)
    return f'<path transform="translate({(WIDTH - w) / 2:.1f} {baseline})" fill="{fill}" d="{d}"/>'


def main():
    logo = (ASSETS / "logo.svg").read_text()
    logo_inner = re.search(r"</title>(.*)</svg>", logo, re.S).group(1)
    logo_w = 420
    logo_h = logo_w * 320 / 545  # logo.svg viewBox is 545 x 320 from (225, 315)

    tagline = centred(FONTS / "cormorant-garamond-latin-600-normal.woff2", TAGLINE, 58, 430, PEARL)
    place = centred(FONTS / "inter-latin-500-normal.woff2", PLACE, 20, 520, MIST, track=4)

    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{HEIGHT}" viewBox="0 0 {WIDTH} {HEIGHT}" role="img" aria-label="Aura Shots. Not just photos, it's an aura. Kigali, Rwanda.">
<title>Aura Shots - Not just photos...it's an aura - Kigali, Rwanda</title>
<rect width="{WIDTH}" height="{HEIGHT}" fill="{NOIR}"/>
<!-- Safe area 60,32 to 1140,598 (1080x566). Text is outlined so no font is needed to render. Generated by scripts/design/og_image.py. -->
<svg x="{(WIDTH - logo_w) / 2}" y="88" width="{logo_w}" height="{logo_h:.1f}" viewBox="225 315 545 320">{logo_inner}</svg>
{tagline}
<rect x="570" y="458" width="60" height="4" rx="2" fill="{PINK}"/>
{place}
</svg>'''
    svg_file = ASSETS / "og-image.svg"
    svg_file.write_text(svg)
    subprocess.run(
        ["inkscape", str(svg_file), "--export-type=png",
         f"--export-filename={ASSETS / 'og-image.png'}", f"--export-width={WIDTH}"],
        check=True,
    )
    print(f"Wrote {svg_file} and {ASSETS / 'og-image.png'}")


if __name__ == "__main__":
    main()
